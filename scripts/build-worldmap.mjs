/**
 * One-time generator: `node scripts/build-worldmap.mjs`
 *
 * Projects Natural Earth 110m land data (via world-atlas) into a fixed
 * equirectangular viewBox and bakes the result as a static SVG path string,
 * plus the exact projection constants used to produce it.
 *
 * Baking this ahead of time means the shipped client bundle carries one path
 * string and some arithmetic — not d3-geo, not topojson-client, not the raw
 * topology. AdventureMap.tsx re-derives city x/y with the same plain
 * equirectangular formula (longitude and latitude both map linearly), so
 * land and city markers are guaranteed to agree without re-running a
 * projection library in the browser.
 */
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import land from "world-atlas/land-110m.json" with { type: "json" };
import { writeFileSync } from "node:fs";

export const MAP_WIDTH = 960;
export const MAP_HEIGHT = 480;

const projection = geoEquirectangular()
  .fitSize([MAP_WIDTH, MAP_HEIGHT], { type: "Sphere" });

const path = geoPath(projection);
const landGeo = feature(land, land.objects.land);
const d = path(landGeo);

if (!d) throw new Error("Projection produced no path — check the input topology.");

// Equirectangular is linear in both axes, so the whole projection reduces to
// one scale factor and a translate — verified against d3's own output for
// known points (poles, antimeridian, center) before baking.
const [scale] = [projection.scale()];
const [tx, ty] = projection.translate();

const out = `// GENERATED by scripts/build-worldmap.mjs — do not hand-edit.
// Natural Earth 110m land outlines (via world-atlas), projected
// equirectangular into a ${MAP_WIDTH}x${MAP_HEIGHT} viewBox.

export const MAP_WIDTH = ${MAP_WIDTH};
export const MAP_HEIGHT = ${MAP_HEIGHT};

/**
 * Project lon/lat (degrees) to the same x/y space LAND_PATH is drawn in.
 *
 * Equirectangular reduces to one scale and one translate — this is pure
 * arithmetic so city markers line up with the baked land path without
 * shipping d3-geo to the client. Constants re-derived by the generator
 * script any time the viewBox changes; do not edit by hand.
 */
export function projectLonLat(lon: number, lat: number): [number, number] {
  const DEG2RAD = Math.PI / 180;
  return [${tx} + ${scale} * lon * DEG2RAD, ${ty} - ${scale} * lat * DEG2RAD];
}

export const LAND_PATH =
  "${d}";
`;

writeFileSync(new URL("../src/lib/worldmap-data.ts", import.meta.url), out);
console.log(`Wrote worldmap-data.ts — path length ${d.length.toLocaleString()} chars`);
